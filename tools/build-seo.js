#!/usr/bin/env node
/*
 * Cibo Napoli: writes the search-engine data from js/config.js and js/menu-data.js.
 *   - schema.org Restaurant + Menu (JSON-LD) between the SCHEMA markers in index.html
 *   - the site address in canonical / hreflang / og:url / og:image (index.html and the text pages)
 *   - sitemap.xml and robots.txt
 * Run after changing the details, the menu or the domain:  node tools/build-seo.js
 */
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const root = path.join(__dirname, "..");
const ctx = { window: {} };
vm.createContext(ctx);
["js/config.js", "js/menu-data.js"].forEach((f) => vm.runInContext(fs.readFileSync(path.join(root, f), "utf8"), ctx));
const C = ctx.window.CONFIG;
const MENU = ctx.window.MENU;
const SITE = C.locations[0];
const base = C.siteUrl.replace(/\/$/, "");
const L = (v) => (typeof v === "string" ? v : v.fr);

const restaurant = {
  "@type": "Restaurant",
  "@id": `${base}/#restaurant`,
  name: SITE.googleName,
  url: `${base}/`,
  logo: `${base}/assets/brand/logo-green-1200.png`,
  image: `${base}${C.shareImage}`,
  telephone: SITE.phoneIntl,
  servesCuisine: ["Italienne", "Pizza napolitaine", "Pâtes fraîches"],
  priceRange: "25 – 95 DH",
  currenciesAccepted: "MAD",
  paymentAccepted: "Espèces, carte bancaire (au restaurant)",
  address: {
    "@type": "PostalAddress",
    ...(SITE.streetAddress ? { streetAddress: SITE.streetAddress } : {}),
    addressLocality: SITE.locality,
    ...(SITE.postalCode ? { postalCode: SITE.postalCode } : {}),
    addressCountry: "MA",
  },
  geo: { "@type": "GeoCoordinates", latitude: SITE.location.lat, longitude: SITE.location.lng },
  hasMap: SITE.googleMapsUrl,
  sameAs: [SITE.instagram],
  openingHoursSpecification: [{
    "@type": "OpeningHoursSpecification",
    dayOfWeek: ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"],
    opens: C.hours.open,
    closes: C.hours.close === "00:00" ? "23:59" : C.hours.close,
  }],
  hasMenu: { "@id": `${base}/#menu` },
  acceptsReservations: `${base}/reserver/`,
  potentialAction: { "@type": "OrderAction", target: `${base}/commander/`, deliveryMethod: ["http://purl.org/goodrelations/v1#DeliveryModeOwnFleet", "http://purl.org/goodrelations/v1#DeliveryModePickUp"] },
};
const menu = {
  "@type": "Menu",
  "@id": `${base}/#menu`,
  url: `${base}/commander/`,
  name: "La carta",
  inLanguage: "fr",
  hasMenuSection: MENU.map((cat) => ({
    "@type": "MenuSection",
    name: L(cat.name),
    hasMenuItem: cat.items.map((it) => ({
      "@type": "MenuItem",
      name: L(it.name),
      ...(it.desc ? { description: it.desc.fr } : {}),
      ...(it.price != null ? { offers: { "@type": "Offer", price: String(it.price), priceCurrency: "MAD" } } : {}),
    })),
  })),
};
const website = { "@type": "WebSite", "@id": `${base}/#website`, url: `${base}/`, name: C.name, inLanguage: ["fr", "en"] };
const json = JSON.stringify({ "@context": "https://schema.org", "@graph": [restaurant, menu, website] }, null, 2);

const fixUrls = (html) => html.replace(/https:\/\/[a-z0-9.-]+\.(?:vercel\.app|ma|com)(?=\/)/g, (m) => (/(google|instagram|openstreetmap|cndp|wa\.me|supabase)/.test(m) ? m : base));

let index = fs.readFileSync(path.join(root, "index.html"), "utf8");
index = index.replace(/<!-- SCHEMA:START[\s\S]*?<!-- SCHEMA:END -->/,
  `<!-- SCHEMA:START (generated by tools/build-seo.js from js/config.js and js/menu-data.js; do not edit by hand) -->\n  <script type="application/ld+json">\n${json.replace(/^/gm, "  ")}\n  </script>\n  <!-- SCHEMA:END -->`);
fs.writeFileSync(path.join(root, "index.html"), fixUrls(index));
["commander/index.html", "reserver/index.html", "confidentialite/index.html", "conditions/index.html"].forEach((f) => {
  const p = path.join(root, f);
  fs.writeFileSync(p, fixUrls(fs.readFileSync(p, "utf8")));
});

const today = new Date().toISOString().slice(0, 10);
const urls = [["/", "1.0"], ["/?lang=en", "0.8"], ["/commander/", "0.9"], ["/commander/?lang=en", "0.7"], ["/reserver/", "0.8"], ["/reserver/?lang=en", "0.6"], ["/confidentialite/", "0.3"], ["/conditions/", "0.3"]];
fs.writeFileSync(path.join(root, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls.map(([u, p]) => `  <url>
    <loc>${base}${u.replace("&", "&amp;")}</loc>
    <lastmod>${today}</lastmod>
    <priority>${p}</priority>${/^\/(commander\/|reserver\/)?(\?lang=en)?$/.test(u) ? `
    <xhtml:link rel="alternate" hreflang="fr" href="${base}${u.replace("?lang=en", "")}"/>
    <xhtml:link rel="alternate" hreflang="en" href="${base}${u.replace("?lang=en", "")}?lang=en"/>` : ""}
  </url>`).join("\n")}
</urlset>
`);
fs.writeFileSync(path.join(root, "robots.txt"), `User-agent: *
Allow: /
Disallow: /commandes/
Disallow: /avis/

Sitemap: ${base}/sitemap.xml
`);
console.log(`SEO data written for ${base}`);
